VILLAGE_K = 0.55
BLEND_TO = 600.0             # пикселей: дальше — 1:1


def _smoothstep(a, b, x):
    t = min(max((x - a) / (b - a), 0.0), 1.0)
    return t * t * (3.0 - 2.0 * t)


def P(px, py):
    """Пиксель концепта → метры мира (x — восток, y — север)."""
    dx, dy = px - ORIGIN[0], ORIGIN[1] - py
    r = math.hypot(dx, dy)
    if r < 1e-6:
        return 0.0, 0.0
    if r <= VILLAGE_R:
        r2 = r * VILLAGE_K
    else:
        shift = VILLAGE_R * (1.0 - VILLAGE_K)
        r2 = r - shift * (1.0 - _smoothstep(VILLAGE_R, BLEND_TO, r))
    return dx / r * r2, dy / r * r2


def PL(points):
    return [P(x, y) for x, y in points]


